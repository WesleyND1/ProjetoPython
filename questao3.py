# Algoritmo Calcular a Área de um Triângulo

#Declarando as variáveis
base = 0.00
altura = 0.00
areaT = 0.00

#Inicio
base = float(input("Digite o valor da base em metros: "))
altura = float(input("Digite o valor da altura em metros: "))
areaT = (base * altura) / 2
print("A área do Triângulo é de: ", areaT, "m²")
